#!/bin/sh
# Regenerates the extension icons and the embedded header logo from the app's public logo.
# Needs macOS (`sips` and `base64`). Run from anywhere: sh extensions/sga-grades/tools/make-icons.sh
set -eu
here="$(cd "$(dirname "$0")/.." && pwd)"
logo="$here/../../public/logo2.png"
for size in 16 32 48 128; do
	sips -z "$size" "$size" "$logo" --out "$here/icons/icon-$size.png" >/dev/null
done
# The panel loads its logo from this data URI, so the extension needs no web-accessible resources.
sips -z 64 64 "$logo" --out /tmp/aura-sga-logo-64.png >/dev/null
{
	echo '// Generated by tools/make-icons.sh from public/logo2.png. Do not edit by hand.'
	printf 'window.AuraSgaBrand = { logo: "data:image/png;base64,%s" };\n' "$(base64 < /tmp/aura-sga-logo-64.png | tr -d '\n')"
} > "$here/brand.js"
rm -f /tmp/aura-sga-logo-64.png
echo "icons and brand.js updated"
